/**
 * getSuggestions — Return up to 3 dictionary words matching the prefix.
 *
 * @param {string} prefix  - The current word buffer (case-insensitive)
 * @param {string[]} dict  - Dictionary array (defaults to built-in DICTIONARY)
 * @returns {string[]} Up to 3 matching words, sorted by length (shortest first)
 */
export function getSuggestions(prefix, dict = DICTIONARY) {
  if (!prefix || prefix.length === 0) return [];

  const lower = prefix.toLowerCase();

  const matches = dict.filter((w) => w.toLowerCase().startsWith(lower));

  // Sort by length (shortest first), then alphabetically
  matches.sort((a, b) => a.length - b.length || a.localeCompare(b));

  return matches.slice(0, 3);
}

